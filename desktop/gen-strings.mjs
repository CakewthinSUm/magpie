// Generates the desktop app's string table from the page's own i18n.js.
//
// The WinUI pages say the same words the page does (they were ported from
// it), so their translations are already there: this reads i18n.js's I18N,
// keeps the keys the app actually says, and writes them as a C# dictionary
// per language. A key i18n.js doesn't know stays English (the page falls
// back to English too), so a half-translated language still works.
//
//   node desktop/gen-strings.mjs
//
// Run it after changing a string in the pages: the app's table is generated,
// not edited by hand, so a word the page already translates is never written
// twice.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.dirname(here);
const assets = path.join(repo, "internal/gui/assets");

// the page's translations, as its tests load them
const src = fs.readFileSync(path.join(assets, "i18n.js"), "utf8");
const ctx = { console };
vm.createContext(ctx);
vm.runInContext(src + "\nthis.I18N = I18N;", ctx);
const I18N = ctx.I18N;

// the app's own words, for what the page has no key for (its wording differs,
// or it kept the sentence in a tooltip): merged after, so a word the page
// translates is never written twice
const extraFile = path.join(here, "strings-extra.json");
if (fs.existsSync(extraFile)) {
  const extra = JSON.parse(fs.readFileSync(extraFile, "utf8"));
  for (const [lang, table] of Object.entries(extra)) {
    if (lang.startsWith("_") || !I18N[lang]) continue;
    for (const [key, value] of Object.entries(table)) {
      if (value) I18N[lang][key] = value;
    }
  }
}

// Every key the page translates, not only the ones a source file mentions:
// a word reaches the app from XAML, from code, and from a tuple inside a
// choice row, and filtering by a regex over the sources missed the last
// kind. The table is a lookup, so a key the app never says costs nothing
// but its line.
const keys = [...new Set(Object.values(I18N).flatMap((lang) => Object.keys(lang)))].sort();

const langs = Object.keys(I18N);
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n");

let out = `// Generated by desktop/gen-strings.mjs from internal/gui/assets/i18n.js.
// Do not edit: run the script after changing a word the pages say.
//
// The keys are the page's own (the English text as app.js writes it), so a
// word the page already translates is the app's translation too. A key
// i18n.js doesn't know is absent here and the caller keeps its English.
using System.Collections.Generic;

namespace Magpie.Desktop;

internal static class Strings
{
    /// <summary>Every language the page knows, by the id Settings uses.</summary>
    public static readonly string[] Languages = [${langs.map((l) => `"${l}"`).join(", ")}];

    private static readonly Dictionary<string, Dictionary<string, string>> Table = new()
    {
`;
for (const lang of langs) {
  out += `        ["${lang}"] = new()\n        {\n`;
  for (const key of keys) {
    const value = I18N[lang][key];
    if (value === undefined) continue;
    out += `            ["${esc(key)}"] = "${esc(value)}",\n`;
  }
  out += `        },\n`;
}
out += `    };

    /// <summary>The table for a language id, or null for English (which is
    /// the text itself) or a language the page doesn't know.</summary>
    public static Dictionary<string, string>? For(string? lang) =>
        lang is { Length: > 0 } && Table.TryGetValue(lang, out var t) ? t : null;
}
`;

const target = path.join(here, "Magpie.Desktop/Strings.cs");
fs.writeFileSync(target, out);
console.log(`${keys.length} keys x ${langs.length} languages -> ${path.relative(repo, target)} (${(out.length / 1e6).toFixed(1)} MB)`);
